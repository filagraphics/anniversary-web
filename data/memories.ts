/** All photos of a chapter, featured photos first. */
export function getMemoriesByChapter(chapter: ChapterId): Memory[] {
  const inChapter = memories.filter((memory) => memory.chapter === chapter);
  return [...inChapter.filter((m) => m.featured), ...inChapter.filter((m) => !m.featured)];
}
